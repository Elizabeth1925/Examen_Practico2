const {chromium}=require('playwright-core')
const assert=require('node:assert/strict')
const path=require('node:path')
;(async()=>{
  const etapa=process.argv[2], despues=etapa==='despues'
  const directorio=path.join(__dirname,'..','evidencias',etapa)
  const browser=await chromium.launch({channel:'msedge',headless:true})
  try {
    const page=await browser.newPage({viewport:{width:390,height:844},locale:'es-EC'})
    const fallos=[]
    page.on('pageerror',e=>fallos.push(e.message))
    const foto=nombre=>page.screenshot({path:path.join(directorio,nombre+'.png'),fullPage:true})
    const btn=nombre=>page.getByRole('button',{name:nombre,exact:true})
    await page.goto('http://127.0.0.1:4173'+(despues?'/':'/evaluacion/v1/'))
    await page.locator('article').first().waitFor()
    assert.equal(await page.locator('article').count(),3)
    await foto('seleccion')
    await page.getByLabel('Docente o asignatura').fill('bases')
    await page.locator('article button').click()
    await page.getByLabel('Modalidad').selectOption('Virtual')
    await page.getByLabel('Fecha',{exact:true}).fill('2099-05-06')
    await btn('Revisar reserva').click()
    assert.equal(await page.getByRole('alert').innerText(),'Selecciona un horario.')
    console.log('Foco al detectar hora vacía:',await page.evaluate(()=>document.activeElement.name || document.activeElement.textContent))
    await foto('error-horario')
    if(despues) assert.equal(await page.evaluate(()=>document.activeElement.name),'hora')
    await page.locator('[name=hora]').selectOption('09:00')
    await btn('Revisar reserva').click()
    await btn('Volver a editar').click()
    assert.equal(await page.locator('[name=hora]').inputValue(),'09:00')
    await btn('Revisar reserva').click()
    await btn('Confirmar reserva').click()
    await page.reload()
    await btn('Mis reservas').click()
    await btn('Modificar').click()
    await page.locator('[name=hora]').selectOption('14:00')
    await btn('Revisar reserva').click()
    await btn('Guardar cambios').click()
    assert.equal(await page.locator('article').count(),1)
    assert.match(await page.locator('article').innerText(),/14:00/)
    await btn('Cancelar').click()
    await btn('Conservar reserva').click()
    await btn('Cancelar').click()
    await btn('Confirmar cancelación').click()
    assert.match(await page.locator('article').innerText(),/Cancelada/)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await page.setViewportSize({width:1280,height:800})
    await btn('Buscar tutoría').click()
    await page.getByLabel('Docente o asignatura').fill('')
    if(despues) await foto('escritorio')
    await page.goto('http://127.0.0.1:4173/ux/prototipo/')
    await btn('Mis reservas').click()
    assert.match(await page.locator('main').innerText(),/Aún no tienes reservas/)
    assert.deepEqual(fallos,[])
    console.log('Flujo de interfaz completo, almacenamiento, retorno y prototipo verificados.',etapa)
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})




